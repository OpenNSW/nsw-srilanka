package payloadschema

import (
	"encoding/json"
	"fmt"
	"strings"
)

// listSwitch says whether the user may add rows to a list and remove its rows.
type listSwitch struct {
	addable, removable bool
}

// listSwitches holds, by path, the switches of the lists a form's UI schema
// shows, read the way the trader app's renderers (ui-packages' radixRenderers)
// show them:
//
//   - A Control shows a list with "Add" and "Remove" unless its options set
//     addable or removable to false. The list's rows are laid out by the
//     control's options.detail, whose scopes are relative to a row, or, with no
//     detail, by a layout the renderer generates: a Control for each property
//     of the row, so a list in a row is shown with both switches on. An object
//     has no renderer of its own, so nothing inside it is shown that way.
//   - A form without a UI schema gets a generated one, which shows every list
//     with both switches on, inside objects too.
//   - A list no control shows can't be added to or removed from.
//   - A list several controls show allows what any of them allows.
type listSwitches struct {
	controls  map[string]listSwitch
	generated []generatedLayout
}

// generatedLayout is a layout the renderer generates for the value at path.
// objects is whether it shows the lists inside objects too.
type generatedLayout struct {
	at      string
	objects bool
}

// parseListSwitches reads the lists uiSchema shows. An absent or null UI
// schema is generated by the renderer.
func parseListSwitches(uiSchema json.RawMessage) (listSwitches, error) {
	l := listSwitches{controls: make(map[string]listSwitch)}
	var ui any
	if len(uiSchema) > 0 {
		if err := json.Unmarshal(uiSchema, &ui); err != nil {
			return listSwitches{}, fmt.Errorf("payload schema: ui schema: %w", err)
		}
	}
	if ui == nil {
		l.generated = append(l.generated, generatedLayout{at: "", objects: true})
		return l, nil
	}
	l.walk(ui, "")
	return l, nil
}

// walk records the controls in the UI schema element el, whose scopes are
// relative to the value at base.
func (l *listSwitches) walk(el any, base string) {
	m, ok := el.(map[string]any)
	if !ok {
		return
	}
	if m["type"] == "Control" {
		if scope, ok := m["scope"].(string); ok {
			if path, ok := scopePath(base, scope); ok {
				l.control(path, m["options"])
			}
		}
	}
	if elements, ok := m["elements"].([]any); ok {
		for _, e := range elements {
			l.walk(e, base)
		}
	}
}

// control records a Control showing the value at path with options. Only a
// list uses what is recorded; for anything else it is never asked for.
func (l *listSwitches) control(path string, options any) {
	// Options that aren't an object set nothing, as for the renderer: both
	// switches stay on.
	opts, _ := options.(map[string]any)
	on := func(name string) bool {
		v, ok := opts[name].(bool)
		return !ok || v
	}
	sw := l.controls[path]
	sw.addable = sw.addable || on("addable")
	sw.removable = sw.removable || on("removable")
	l.controls[path] = sw

	switch detail := opts["detail"].(type) {
	case nil:
		l.generated = append(l.generated, generatedLayout{at: path + "/[]"})
	case map[string]any:
		l.walk(detail, path+"/[]")
	}
	// Any other detail (such as a string) is not a layout the renderer can
	// show, so the rows show nothing.
}

// at returns the switches of the list at path.
func (l listSwitches) at(path string) listSwitch {
	sw := l.controls[path]
	for _, g := range l.generated {
		if g.shows(path) {
			sw = listSwitch{addable: true, removable: true}
		}
	}
	return sw
}

// shows reports whether the generated layout shows the list at path. It shows
// its value: each property gets a Control, and a value that isn't an object
// one Control of its own. A list shown that way has both switches on and its
// rows a generated layout of their own; an object shown that way lays out its
// properties only when g.objects, since otherwise it has no renderer.
func (g generatedLayout) shows(path string) bool {
	if path == g.at {
		return true
	}
	prefix := g.at + "/"
	if !strings.HasPrefix(path, prefix) {
		return false
	}
	// laidOut is whether the properties of the value reached so far are shown.
	laidOut, objects := true, g.objects
	for _, token := range strings.Split(strings.TrimPrefix(path, prefix), "/") {
		if token == "[]" {
			// The rows of a shown list, laid out by the renderer.
			laidOut, objects = true, false
			continue
		}
		if !laidOut {
			return false // inside an object, which has no renderer
		}
		laidOut = objects
	}
	return true
}

// scopePath returns the path of the value a Control's scope points to, from
// the value at base: "#/properties/a/properties/b" is base+"/a/b", and an
// "items" step is a row ("/[]"). A scope in any other form is not followed.
func scopePath(base, scope string) (string, bool) {
	if scope == "#" {
		return base, true
	}
	rest, ok := strings.CutPrefix(scope, "#/")
	if !ok {
		return "", false
	}
	path := base
	tokens := strings.Split(rest, "/")
	for i := 0; i < len(tokens); i++ {
		switch tokens[i] {
		case "properties":
			if i+1 >= len(tokens) {
				return "", false
			}
			i++
			path += "/" + tokens[i]
		case "items":
			path += "/[]"
		default:
			return "", false
		}
	}
	return path, true
}
